#!/usr/bin/env python3
"""
Dump the resolved configuration of every model in the registry.

Produces ``benchmarks/results/configs/model_configs.md``: a single table
of the architectural hyperparameters that matter for the comparison
(parameter count, hidden size, depth, heads, context window, vocabulary,
and the architecture family), plus the exact configuration used for the
from-scratch checkpoints.

This is the "model/configuration details" section of the report: it lets a
reader confirm that the comparison is between models with the properties
claimed, without re-running anything.

Examples
--------
    python benchmarks/scripts/05_dump_configs.py
"""

from __future__ import annotations

import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
sys.path.insert(0, _ROOT)
sys.path.insert(0, os.path.join(_ROOT, "benchmarks", "src"))

from model_registry import REGISTRY  # noqa: E402

OUT_DIR = os.path.join(_ROOT, "benchmarks", "results", "configs")


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def _legacy_state_spaces_config(model_id: str):
    """
    Read the raw ``config.json`` of a legacy ``state-spaces`` repo.

    Those repos predate the hub format and have no ``model_type`` key, so
    ``AutoConfig`` rejects them. We read the raw JSON instead.
    """
    try:
        from huggingface_hub import snapshot_download

        path = snapshot_download(
            model_id, allow_patterns=["*.json", "*.txt", "*.safetensors", "*.bin"]
        )
        with open(os.path.join(path, "config.json")) as f:
            c = json.load(f)
    except Exception as e:  # noqa: BLE001
        return {"_error": f"{type(e).__name__}: {str(e)[:80]}"}

    layer = (c.get("ssm_cfg") or {}).get("layer", "Mamba")
    return {
        "model_type": f"mamba{2 if layer.lower().startswith('mamba2') else ''}",
        "vocab_size": c.get("vocab_size"),
        "hidden": c.get("d_model"),
        "layers": c.get("n_layer"),
        "heads": "n/a (SSM: no attention heads)",
        "kv_heads": "n/a",
        "intermediate": c.get("d_intermediate") or "n/a",
        "max_positions": "unbounded (recurrent)",
        "norm": "RMSNorm" if c.get("rms_norm") else "LayerNorm",
        "pos_enc": "none (recurrent, position-independent)",
        "tie": c.get("tie_embeddings", "n/a"),
    }


def hf_config(model_id: str):
    """Best-effort extraction of the interesting fields from a HF config."""
    from transformers import AutoConfig

    try:
        c = AutoConfig.from_pretrained(model_id, trust_remote_code=False)
    except Exception:  # noqa: BLE001
        return _legacy_state_spaces_config(model_id)

    def get(*names, default="n/a"):
        for n in names:
            if hasattr(c, n) and getattr(c, n) is not None:
                return getattr(c, n)
        return default

    is_rms = getattr(c, "rms_norm", False)
    has_ln = any(
        hasattr(c, n) for n in ("layer_norm_eps", "layer_norm_epsilon", "layer_norm_type")
    )
    return {
        "model_type": getattr(c, "model_type", "n/a"),
        "vocab_size": get("vocab_size"),
        "hidden": get("hidden_size", "n_embd", "d_model"),
        "layers": get("num_hidden_layers", "n_layer", "n_layers"),
        "heads": get("num_attention_heads", "n_head", "n_heads"),
        "kv_heads": get("num_key_value_heads", "n_head", default="n/a"),
        "intermediate": get("intermediate_size", "ffn_dim", "d_ff", default="n/a"),
        "max_positions": get("max_position_embeddings", "n_positions", "max_seq_len"),
        "norm": "RMSNorm" if is_rms else ("LayerNorm" if has_ln else "n/a"),
        "pos_enc": "RoPE" if getattr(c, "rope_theta", None) or
                   getattr(c, "rope_scaling", None) is not None else
                   ("learned-absolute" if getattr(c, "max_position_embeddings", None) else "n/a"),
        "tie": get("tie_word_embeddings", default="n/a"),
    }


def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    lines = [
        "# Model configuration details",
        "",
        "Auto-generated by `benchmarks/scripts/05_dump_configs.py`.",
        "",
        "## Baselines",
        "",
    ]

    rows = []
    raw = {}
    for b in REGISTRY:
        if not b.hf_id:
            continue
        cfg = hf_config(b.hf_id)
        raw[b.key] = cfg
        rows.append([
            f"`{b.key}`", b.hf_id, b.tier,
            cfg.get("model_type"), cfg.get("hidden"), cfg.get("layers"),
            cfg.get("heads"), cfg.get("intermediate"), cfg.get("vocab_size"),
            cfg.get("max_positions"), cfg.get("norm"), cfg.get("pos_enc"),
        ])

    lines.append(md_table(
        ["Key", "Repo", "Tier", "type", "d_model", "layers", "heads", "d_ff",
         "vocab", "ctx", "norm", "pos"],
        rows,
    ))
    lines.append("")

    lines.append("## From-scratch checkpoints (ours)")
    lines.append("")
    ck_dir = os.path.join(_ROOT, "benchmarks", "checkpoints", "matched_params")
    ours_rows = []
    for fn in ("hskm.pt", "gpt2.pt"):
        p = os.path.join(ck_dir, fn)
        if not os.path.exists(p):
            ours_rows.append([f"`{fn}`", "-", "-", "-", "-", "-", "not trained yet"])
            continue
        import torch

        ck = torch.load(p, map_location="cpu", weights_only=False)
        cfg = ck.get("config", {})
        ours_rows.append([
            f"`{fn}`",
            f"{ck.get('params', 0) / 1e6:.1f}M",
            f"{ck.get('tokens_seen', 0):,}",
            cfg.get("d_model", cfg.get("n_embd", "-")),
            cfg.get("n_layers", cfg.get("n_layer", "-")),
            cfg.get("n_heads", cfg.get("n_head", "-")),
            f"val_ppl={ck.get('val_ppl', float('nan')):.2f}",
        ])
    lines.append(md_table(
        ["Checkpoint", "Params", "Tokens seen", "d_model", "layers", "heads", "Result"],
        ours_rows,
    ))
    lines.append("")

    lines.append("## Raw config JSON")
    lines.append("")
    lines.append("```json")
    lines.append(json.dumps(raw, indent=2))
    lines.append("```")
    lines.append("")

    out_path = os.path.join(OUT_DIR, "model_configs.md")
    with open(out_path, "w") as f:
        f.write("\n".join(lines))

    with open(os.path.join(OUT_DIR, "model_configs.json"), "w") as f:
        json.dump(raw, f, indent=2)

    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
